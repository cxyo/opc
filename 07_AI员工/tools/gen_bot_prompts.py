def io_to_block(io_text):
    """把输入输出表拆成输入部分。"""
    lines = [l for l in io_text.split("\n") if l.strip().startswith("|")]
    if not lines:
        return "- （无显式输入定义）"
    out = []
    for l in lines:
        cells = [c.strip() for c in l.strip().strip("|").split("|")]
        if len(cells) >= 2 and cells[0] not in ("类型", "---"):
            out.append(f"- **{cells[0]}**：{cells[1]}")
    return "\n".join(out)


def table_to_block(tbl_text):
    """把失败处理表转成 markdown 表格块（含表头）。"""
    rows = []
    for l in tbl_text.split("\n"):
        s = l.strip()
        if not s.startswith("|"):
            continue
        if set(s) <= set("|- "):   # 分隔行
            continue
        rows.append(s)
    if not rows:
        return "| 情况 | 处理 |\n|------|------|\n| 缺输入时 | 输出「信息不足，无法处理」并列出缺什么 |"
    # 补表头（源数据里表头被剥掉了）
    if not rows[0].startswith("| 情况"):
        rows = ["| 情况 | 处理 |", "|------|------|"] + rows
    return "\n".join(rows)


def renumber(constraints_text):
    """重新编号约束列表，去掉原文自带的序号，避免出现 1. 1. 这种重复。"""
    out = []
    for l in constraints_text.split("\n"):
        s = l.strip()
        if not s:
            continue
        # 去掉原文可能带的 "1. " "2、 " "- " 等前缀
        import re
        s = re.sub(r"^(\d+[.、)]|[-*])\s*", "", s)
        out.append(s)
    return "\n".join(f"{i+1}. {s}" for i, s in enumerate(out))


