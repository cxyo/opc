def main():
    ledger = mt.load()
    items = {it["id"]: it for it in ledger["素材"]}

    applied = learned = missed = 0
    for sid, L in LEARNINGS.items():
        iid = "v_%s" % sid
        it = items.get(iid)
        if not it:
            print("  ✗ 台账里找不到 %s" % iid)
            missed += 1
            continue

        it["值得借鉴"] = L["borrow"]
        it["主要内容"] = L["content"]
        it["用在哪"] = L["where"]
        it["效果"] = L["effect"]
        it["待用"] = L["todo"]
        it["学习状态"] = L["status"]

        if L["status"] == "applied":
            applied += 1
            # 已落地的写进使用记录（不重复写）
            rec = {"用在哪": L["where"], "效果": L["effect"], "时间": "2026-10-31"}
            recs = it.get("使用记录") or []
            if not any(r.get("用在哪") == rec["用在哪"] for r in recs):
                recs.append(rec)
            it["使用记录"] = recs
        else:
            learned += 1

    ledger["素材"] = list(items.values())
    ok = mt.save(ledger)
    print("台账保存：%s" % ("成功" if ok else "失败"))
    print("已落地 applied：%d 条" % applied)
    print("已学待用 learned：%d 条" % learned)
    if missed:
        print("未匹配：%d 条" % missed)

    # 同步生成学习成果 Markdown
    n = mt.sync_outcomes()
    print("学习成果文档同步：%d 篇" % n)


if __name__ == "__main__":
    main()
