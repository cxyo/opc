def build() -> Dict[str, Any]:
    """读取原始抓取结果 + 结论，写入台账。"""
    meta_path = os.path.join(ROOT, "08_可运行系统", "tools", "sph_meta.json")
    if not os.path.isfile(meta_path):
        return {"ok": False, "error": "找不到 sph_meta.json"}

    with open(meta_path, "r", encoding="utf-8") as f:
        rows = json.load(f)

    added = 0
    applied = 0
    note_count = 0

    for r in rows:
        if not isinstance(r, dict) or not r.get("ok"):
            continue
        sid = r.get("id")
        if not sid:
            continue

        # 封面归位到素材库
        cover_rel = ""
        src = os.path.join(ROOT, "08_可运行系统", "tools", "sph_covers",
                           "%s.jpg" % sid)
        dst = os.path.join(M.raw_dir("video"), "%s.jpg" % sid)
        if os.path.isfile(src) and not os.path.isfile(dst):
            try:
                import shutil
                shutil.copy2(src, dst)
            except Exception:
                pass
        if os.path.isfile(dst):
            cover_rel = os.path.relpath(dst, M.lib_dir())

        title = (r.get("title") or "").strip()
        author = r.get("author") or ""
        date = r.get("date") or ""
        lk = num(r.get("like"))
        cm = num(r.get("comment"))
        fv = num(r.get("fav"))
        fw = num(r.get("forward"))

        note = NOTES.get(sid, {})
        cat = guess_category(title, author)

        # 有明确结论的 → 已用/已学；只有元信息的 → 待学
        if note.get("用在哪"):
            status = "applied"
            applied += 1
        elif note:
            status = "learned"
            note_count += 1
        else:
            status = "pending"

        item = {
            "id": "v_%s" % sid,
            "类型": "video",
            "标题": title,
            "作者": author,
            "日期": date,
            "链接": r.get("url") or ("https://weixin.qq.com/sph/%s" % sid),
            "平台": "视频号",
            "来源渠道": "用户提供的视频号链接",
            "类目": "%s %s" % (cat, CATEGORY_NAMES.get(cat, "")),
            "封面": cover_rel,
            "数据": {"点赞": lk, "评论": cm, "收藏": fv, "转发": fw,
                     "转赞比": round(fw / lk, 2) if lk else 0},
            "学习状态": status,
            "主要内容": note.get("主要内容", ""),
            "值得借鉴": note.get("值得借鉴", ""),
            "用在哪": note.get("用在哪", ""),
            "效果": note.get("效果", ""),
            "待用": note.get("待用", ""),
            "使用记录": [],
            "备注": "视频本体未获取（微信预览页只下发封面和文案）；"
                    "分析仅基于元信息与封面实拍，不做推测",
        }

        if item["用在哪"]:
            item["使用记录"] = [{
                "用在哪": item["用在哪"],
                "效果": item["效果"],
                "产出物": "",
                "时间": date or "",
            }]

        before = len(M.all_items())
        M.upsert(item)
        if len(M.all_items()) > before:
            added += 1

    return {
        "ok": True,
        "新增": added,
        "已用": applied,
        "已学": note_count,
        "总数": len(M.all_items()),
    }


def import_doc_assets() -> Dict[str, Any]:
    """把用户提供的**文档类原始资料**也登记进台账。

    这一批不是视频，是文字资料 —— 咸鱼资料包提取出的 75 篇教程/指南。
    它们是"喂进来的原始素材"里最容易被漏掉的部分：
    视频号链接抓了 76 条，文字资料却只躺在 raw/ 目录里，没进过任何索引。

    登记时做两件事：
      ① 原文复制进 素材库/原始素材/文章原文/（原件留一份在库里）
      ② 按关键词自动打上主题标签，便于后期检索
    """
    src = os.path.join(ROOT, "03_知识库", "raw", "咸鱼资料包提取")
    if not os.path.isdir(src):
        return {"ok": False, "error": "找不到 %s" % src, "新增": 0}

    added = 0
    for name in sorted(os.listdir(src)):
        full = os.path.join(src, name)
        if not os.path.isfile(full):
            continue
        stem, ext = os.path.splitext(name)
        if ext.lower() not in (".txt", ".md"):
            continue

        # 原文归位到素材库
        dst = os.path.join(M.raw_dir("article"), name)
        if not os.path.isfile(dst):
            try:
                import shutil
                shutil.copy2(full, dst)
            except Exception:
                pass

        title = stem.replace("_", " ")
        tags = _tags_for(title)

        # 已落地的资料：从"资料包落地对照表"能看出哪些已经变成我们的东西
        landed = _landed_markers(title)

        # ID 规则与 materials._make_id 保持一致：
        # 类型前缀 + 标题前 10 字 + 内容哈希 —— 短且唯一。
        # （2026-10-31 修：原来 ID 用整个标题，拼进文件路径后超 Windows
        #   260 字符上限，学习成果文档静默创建失败。）
        import hashlib
        _key = "|".join([title])
        _h = hashlib.md5(_key.encode("utf-8")).hexdigest()[:6]
        _stem = re.sub(r"[^\w一-鿿]+", "", title)[:10]

        item = {
            "id": "a_%s_%s" % (_stem, _h) if _stem else "a_%s" % _h,
            "类型": "article",
            "标题": title,
            "作者": "咸鱼资料包",
            "日期": "",
            "链接": "",
            "平台": "资料包",
            "来源渠道": "用户提供的第三方资料包（75 篇）",
            "原始文件": os.path.relpath(dst, M.lib_dir()) if os.path.isfile(dst) else "",
            "主题标签": tags,
            "数据": {},
            "学习状态": "applied" if landed else "learned",
            "主要内容": _summarize_doc(full),
            "值得借鉴": landed or "待提炼：可作为内容方法论与 SOP 的参考",
            "用在哪": landed or "",
            "效果": "已并入知识库种子与内容方法论" if landed else "",
            "待用": "" if landed else "尚未提炼成可用资产 —— 可做选题与 SOP 补充",
            "使用记录": [],
        }
        if landed:
            item["使用记录"] = [{
                "用在哪": landed, "效果": "已并入知识库与内容方法论",
                "产出物": "02_知识库种子/", "时间": "",
            }]

        before = len(M.all_items())
        M.upsert(item)
        if len(M.all_items()) > before:
            added += 1

    return {"ok": True, "新增": added}


def _tags_for(title: str) -> List[str]:
    """按关键词打主题标签。"""
    rules = [
        ("视频号", ("视频号",)), ("爆款", ("爆款", "爆火")),
        ("一人公司", ("一人公司", "opc", "OPC")),
        ("私域", ("私域", "朋友圈", "加好友", "微信")),
        ("产品化", ("产品化", "产品设计", "差异化", "价值")),
        ("阅读心理", ("阅读心理", "阅读质量", "新媒体编辑")),
        ("能力", ("能力", "认知", "思维")),
        ("变现", ("变现", "赚钱", "盐值", "知乎", "好物")),
    ]
    out = []
    for tag, words in rules:
        for w in words:
            if w in title:
                out.append(tag)
                break
    return out


def _summarize_doc(path: str, limit: int = 160) -> str:
    """取正文开头做摘要。不做臆测，只是把开头真实内容摘出来。"""
    try:
        with open(path, "r", encoding="utf-8", errors="ignore") as f:
            txt = f.read()
    except Exception:
        return ""
    txt = re.sub(r"\s+", " ", txt).strip()
    return txt[:limit] + ("…" if len(txt) > limit else "")


