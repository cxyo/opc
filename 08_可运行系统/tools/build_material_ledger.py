# ---------------------------------------------------------------- 数字解析


def num(v: Any) -> int:
    """把 '2.1万' / '1,234' / 1234 统一成整数。解析不了就 0，不猜。"""
    if v is None:
        return 0
    if isinstance(v, (int, float)):
        return int(v)
    s = str(v).strip().replace(",", "")
    if not s:
        return 0
    m = re.match(r"^([\d.]+)\s*(万|亿|w|k)?", s, re.I)
    if not m:
        return 0
    try:
        x = float(m.group(1))
    except ValueError:
        return 0
    u = (m.group(2) or "").lower()
    if u in ("万", "w"):
        x *= 10000
    elif u == "亿":
        x *= 100000000
    elif u == "k":
        x *= 1000
    return int(x)


