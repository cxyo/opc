def build_sku_report():
    """生成完整 SKU 报告（Markdown）。"""
    parts = []
    parts.append("# 智能体商品卡 · 货架货品清单\n")
    parts.append(f"> 共 {len(SKUS)} 款可售服务 + {len(LEAD_MAGNETS)} 款引流品。\n")
    parts.append("> 对外名称一律用业务语言，不出现「智能体」「提示词」——\n")
    parts.append("> 客户买的不是 AI，是「有人替我干完这件事」。\n")
    parts.append("\n---\n")
    parts.append("\n## 一、货品总览\n")
    parts.append(sku_table())
    parts.append("\n\n---\n")
    parts.append("\n## 二、引流品（不收费，作用是让客户进得来）\n")
    parts.append("| 引流品 | 为什么它能拉人 |")
    parts.append("|---|---|")
    for m in LEAD_MAGNETS:
        parts.append(f"| {m['name']} | {m['why']} |")
    parts.append("\n\n---\n")
    parts.append("\n## 三、明确不做的（排除清单）\n")
    parts.append("| 不做 | 原因 |")
    parts.append("|---|---|")
    for n in NOT_DOING:
        parts.append(f"| ❌ {n['item']} | {n['why']} |")
    parts.append("\n\n---\n")
    parts.append("\n## 四、完整商品卡\n")
    for s in SKUS:
        parts.append("\n" + sku_detail_md(s) + "\n---\n")
    return "\n".join(parts)


def export_all(outdir):
    """把 SKU 报告与话术脚本导出到目录，返回文件路径列表。"""
    os.makedirs(outdir, exist_ok=True)
    paths = []
    p1 = os.path.join(outdir, "智能体商品卡.md")
    with open(p1, "w", encoding="utf-8") as f:
        f.write(build_sku_report())
    paths.append(p1)

    p2 = os.path.join(outdir, "销售话术脚本.md")
    with open(p2, "w", encoding="utf-8") as f:
        f.write(sell_script_md())
    paths.append(p2)
    return paths
