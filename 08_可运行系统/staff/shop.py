def get_sku(code):
    """按岗位编号取 SKU。"""
    c = (code or "").upper()
    for s in SKUS:
        if s["code"] == c:
            return s
    return None


def list_skus(tier=None):
    """列出全部 SKU，可按层级过滤。"""
    if tier:
        return [s for s in SKUS if s["tier"] == tier]
    return list(SKUS)


def sku_table():
    """返回 Markdown 表格：SKU 总览。"""
    lines = ["| 岗位 | 对外商品名 | 卖谁 | 价格 | 层级 |",
             "|---|---|---|---|---|"]
    for s in SKUS:
        lines.append(f"| {s['code']} | {s['sku']} | {s['buyer'][:18]} | {s['price']} | {s['tier']} |")
    return "\n".join(lines)


