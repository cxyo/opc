def audit_accounts():
    """逐平台跑规则，返回风险清单。"""
    out = []
    for acc in ACCOUNTS:
        p = acc["platform"]
        rules = RULES.get(p, {})
        items = []
        for lv in ("🔴", "🟡", "🟢"):
            for r in rules.get(lv, []):
                items.append({
                    "level": lv, "rule": r["rule"], "detail": r["detail"],
                    "fix": r["fix"],
                })
        red = sum(1 for i in items if i["level"] == "🔴")
        yellow = sum(1 for i in items if i["level"] == "🟡")
        score = max(0, 100 - red * 20 - yellow * 8)
        out.append({**acc, "items": items, "red": red, "yellow": yellow,
                    "score": score})
    return out


